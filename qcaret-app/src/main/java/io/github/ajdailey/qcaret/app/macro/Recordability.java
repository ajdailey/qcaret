package io.github.ajdailey.qcaret.app.macro;

import io.github.ajdailey.qcaret.app.command.CommandId;

/**
 * What a recording does with each command. The switch has no {@code default}, so a new command does
 * not compile until it is classified here.
 */
public enum Recordability {
  /** Recorded as a {@link MacroStep.Command} step. */
  COMMAND,
  /** Recorded as the step its result produces: a find, a dialog's answer or a completion. */
  OWN_STEP,
  /** Runs, is not recorded, and the status bar names it. */
  NOTICE,
  /** Runs and is not recorded: view, window and help commands. */
  SILENT;

  /**
   * Classifies a command.
   *
   * @param command the command
   * @return its class
   */
  public static Recordability of(CommandId command) {
    return switch (command) {
      case UNDO,
          REDO,
          CUT,
          COPY,
          PASTE,
          SELECT_ALL,
          DUPLICATE,
          DELETE_LINE,
          MOVE_LINES_UP,
          MOVE_LINES_DOWN,
          JOIN_LINES,
          UPPER_CASE,
          LOWER_CASE,
          TITLE_CASE,
          SWAP_CASE,
          TRANSPOSE,
          INDENT,
          OUTDENT,
          TOGGLE_LINE_COMMENT,
          TOGGLE_BLOCK_COMMENT,
          TAB_WIDTH_2,
          TAB_WIDTH_4,
          TAB_WIDTH_8,
          INDENT_WITH_SPACES,
          ADD_CARET_ABOVE,
          ADD_CARET_BELOW,
          ADD_NEXT_OCCURRENCE,
          SPLIT_INTO_LINES,
          COLUMN_MODE,
          SELECT_ALL_OCCURRENCES,
          SKIP_OCCURRENCE,
          EXPAND_SELECTION,
          SELECT_LINE,
          UNDO_SELECTION,
          REDO_SELECTION,
          FOLD,
          UNFOLD,
          TOGGLE_FOLD,
          FOLD_ALL,
          UNFOLD_ALL,
          SORT_LINES_ASCENDING,
          SORT_LINES_DESCENDING,
          SORT_LINES_IGNORE_CASE,
          SORT_LINES_NUMERIC,
          REVERSE_LINES,
          REMOVE_DUPLICATE_LINES,
          REMOVE_BLANK_LINES,
          TRIM_TRAILING_WHITESPACE,
          TRIM_LEADING_WHITESPACE,
          INDENT_TO_SPACES,
          INDENT_TO_TABS,
          WRAP_PARAGRAPH,
          PRETTY_PRINT_XML,
          MINIFY_XML,
          CHECK_XML,
          PRETTY_PRINT_JSON,
          MINIFY_JSON,
          CHECK_JSON,
          COPY_XML_PATH,
          COPY_JSON_PATH,
          BASE64_ENCODE,
          BASE64_DECODE,
          URL_ENCODE,
          URL_DECODE,
          XML_ESCAPE,
          XML_UNESCAPE,
          JSON_ESCAPE,
          JSON_UNESCAPE,
          SELECT_TO_MATCHING_BRACKET,
          GO_TO_MATCHING_BRACKET,
          TOGGLE_BOOKMARK,
          NEXT_BOOKMARK,
          PREVIOUS_BOOKMARK,
          CLEAR_BOOKMARKS,
          LINE_ENDING_CRLF,
          LINE_ENDING_LF,
          LINE_ENDING_CR,
          DELETE_WORD_BACK,
          DELETE_WORD_FORWARD,
          CARET_LEFT,
          CARET_RIGHT,
          CARET_UP,
          CARET_DOWN,
          WORD_LEFT,
          WORD_RIGHT,
          LINE_START,
          LINE_END,
          PAGE_UP,
          PAGE_DOWN,
          DOCUMENT_START,
          DOCUMENT_END,
          SELECT_LEFT,
          SELECT_RIGHT,
          SELECT_UP,
          SELECT_DOWN,
          SELECT_WORD_LEFT,
          SELECT_WORD_RIGHT,
          SELECT_LINE_START,
          SELECT_LINE_END,
          SELECT_PAGE_UP,
          SELECT_PAGE_DOWN,
          SELECT_DOCUMENT_START,
          SELECT_DOCUMENT_END,
          BLOCK_LEFT,
          BLOCK_RIGHT,
          BLOCK_UP,
          BLOCK_DOWN,
          INSERT_TAB,
          NEWLINE,
          DELETE_BACK,
          DELETE_FORWARD,
          CANCEL ->
          COMMAND;
      case FIND,
          REPLACE,
          FIND_NEXT,
          FIND_PREVIOUS,
          GO_TO_LINE,
          TAB_WIDTH_OTHER,
          INSERT_DATE_TIME,
          INSERT_NUMBER_SEQUENCE,
          COMPLETE_WORD ->
          OWN_STEP;
      case NEW,
          OPEN,
          SAVE,
          SAVE_AS,
          SAVE_COPY_AS,
          SAVE_ALL,
          CLOSE,
          CLOSE_ALL,
          CLOSE_OTHERS,
          CLOSE_LEFT,
          CLOSE_RIGHT,
          REOPEN_CLOSED,
          OPEN_ALL_CLOSED,
          CLEAR_CLOSED_FILES,
          OPEN_ALL_RECENT,
          CLEAR_RECENT_FILES,
          CLEAN_UP_RECENT,
          RELOAD,
          SET_WORKSPACE,
          QUICK_OPEN,
          PRINT,
          PRINT_SELECTION,
          PRINT_MARKDOWN,
          EXPORT_HTML,
          OPEN_PATH_AT_CARET,
          QUIT,
          READ_ONLY,
          PREFERENCES,
          GO_TO_SYMBOL,
          SWITCH_DOCUMENT,
          GO_BACK,
          GO_FORWARD,
          NEXT_TAB,
          PREVIOUS_TAB,
          NEW_WINDOW,
          MOVE_TO_NEW_WINDOW,
          HYPERSEARCH,
          NEXT_RESULT,
          PREVIOUS_RESULT,
          REPLACE_IN_RESULTS,
          RESTORE_REPLACE_RUN,
          COMPARE_DOCUMENTS,
          COMPARE_WITH_DISK,
          EDIT_BOOKMARK_COMMENT,
          BOOKMARKS_LIST,
          MD5_TEXT,
          MD5_FILES,
          MD5_SELECTION,
          SHA1_TEXT,
          SHA1_FILES,
          SHA1_SELECTION,
          SHA256_TEXT,
          SHA256_FILES,
          SHA256_SELECTION,
          SHA512_TEXT,
          SHA512_FILES,
          SHA512_SELECTION,
          VERIFY_CHECKSUMS,
          OPEN_IN_HEX_VIEWER,
          PLAY_RECORDED_MACRO ->
          NOTICE;
      case WORD_WRAP,
          ZOOM_IN,
          ZOOM_OUT,
          ZOOM_RESET,
          THEME_LIGHT,
          THEME_DARK,
          THEME_SYSTEM,
          SPLIT_HORIZONTAL,
          SPLIT_VERTICAL,
          UNSPLIT,
          FOCUS_OTHER_VIEW,
          MARKDOWN_SOURCE,
          MARKDOWN_SPLIT,
          MARKDOWN_PREVIEW,
          MARKDOWN_CYCLE,
          PREVIEW_BASIC,
          PREVIEW_BROWSER,
          MARKDOWN_SYNC_SCROLL,
          MARKDOWN_OUTLINE,
          RELOAD_GRAMMARS,
          SEARCH_RESULTS,
          SHOW_WHITESPACE,
          SHOW_LINE_ENDINGS,
          OVERVIEW_STRIP,
          LINE_NUMBERS,
          RIGHT_MARGIN,
          INDENT_GUIDES,
          LINE_CHANGES,
          TOOLBAR,
          MEMORY_INDICATOR,
          ALWAYS_ON_TOP,
          COMMAND_PALETTE,
          WORKSPACE_BROWSER,
          FULL_SCREEN,
          MINIMIZE,
          ZOOM_WINDOW,
          DOCUMENT_STATISTICS,
          KEYBOARD_SHORTCUTS,
          COMMAND_LINE_OPTIONS,
          USER_GUIDE,
          TIP_OF_THE_DAY,
          SHOW_LOG,
          DEBUG_LOG_FILE,
          OPEN_LOG_FOLDER,
          OPEN_SETTINGS_FOLDER,
          REPORT_ISSUE,
          CHECK_FOR_UPDATES,
          ABOUT,
          HEX_CYCLE,
          HEX_TEXT,
          HEX_SPLIT,
          HEX_HEX,
          RECORD_MACRO ->
          SILENT;
    };
  }
}
